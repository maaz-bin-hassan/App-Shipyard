import { readdir, readFile } from "node:fs/promises";
import path from "node:path";

export const CANONICAL_SECTIONS = [
  "Goal",
  "Preconditions",
  "Ask",
  "Steps",
  "Verify",
  "Rollback",
  "Never",
];

export const CORE_SECTIONS = ["Goal", "Ask", "Verify", "Never"];
export const FRAGMENT_SECTIONS = ["Preconditions", "Steps", "Rollback"];

const PLATFORM_IDS = new Set(["expo", "flutter", "android", "ios"]);
const STORE_TARGETS = new Set(["play", "appstore"]);
const COMMAND_NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const MANIFEST_FIELDS = [
  "id",
  "name",
  "language",
  "storeTargets",
  "templateDir",
  "commands",
  "envChecks",
  "services",
  "buildTool",
  "releaseTool",
  "stringsFormat",
  "permissionsFile",
];
const SERVICE_KEYS = ["auth", "billing", "analytics", "crashes"];
const OS_KEYS = ["windows", "macos", "linux"];

export async function lintRepository(root) {
  const errors = [];
  const commands = await loadCommands(root, errors);
  const platforms = await loadPlatforms(root, errors);

  for (const platform of platforms) {
    for (const commandName of platform.manifest.commands ?? []) {
      if (!commands.has(commandName)) {
        errors.push(
          `${platform.rel}: commands lists unknown command ${commandName}`,
        );
        continue;
      }
      const fragmentRel = path.posix.join(
        "platforms",
        platform.manifest.id,
        "fragments",
        `${commandName}.md`,
      );
      if (!platform.fragments.has(commandName)) {
        errors.push(
          `${platform.rel}: command ${commandName} is listed but ${fragmentRel} is missing`,
        );
      }
    }

    for (const fragmentName of platform.fragments.keys()) {
      if (!(platform.manifest.commands ?? []).includes(fragmentName)) {
        errors.push(
          `${platform.rel}: fragment ${fragmentName}.md exists but ${fragmentName} is not listed in commands`,
        );
      }
    }

    await lintTemplate(root, platform, errors);
  }

  return errors;
}

export async function loadCommands(root, errors = []) {
  const commands = new Map();
  const dir = path.join(root, "commands");
  let entries = [];
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    errors.push("commands/: directory is missing");
    return commands;
  }

  for (const entry of entries.filter((item) => item.isDirectory()).sort(byName)) {
    if (!COMMAND_NAME.test(entry.name)) {
      errors.push(`commands/${entry.name}: command name must be kebab-case`);
      continue;
    }
    const rel = path.posix.join("commands", entry.name, "COMMAND.md");
    const parsed = await readMarkdown(path.join(dir, entry.name, "COMMAND.md"), rel, errors);
    if (!parsed) continue;
    validateCore(rel, parsed, errors);
    commands.set(entry.name, parsed);
  }

  return commands;
}

export async function loadPlatforms(root, errors = []) {
  const platforms = [];
  const dir = path.join(root, "platforms");
  let entries = [];
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    errors.push("platforms/: directory is missing");
    return platforms;
  }

  for (const entry of entries.filter((item) => item.isDirectory()).sort(byName)) {
    const rel = path.posix.join("platforms", entry.name, "platform.json");
    const manifest = await readManifest(path.join(dir, entry.name, "platform.json"), rel, entry.name, errors);
    const fragments = await loadFragments(path.join(dir, entry.name, "fragments"), entry.name, errors);
    if (manifest) platforms.push({ id: entry.name, rel, manifest, fragments });
  }

  return platforms;
}

export function mergeSections(core, fragment) {
  return {
    Goal: core.sections.Goal,
    Preconditions: fragment.sections.Preconditions,
    Ask: core.sections.Ask,
    Steps: fragment.sections.Steps,
    Verify: core.sections.Verify,
    Rollback: fragment.sections.Rollback,
    Never: core.sections.Never,
  };
}

export function renderCommandFile({
  commandName,
  description,
  argumentHint,
  sections,
  platformId,
  sources,
}) {
  const lines = [
    "---",
    `name: ${yamlString(`ship-${commandName}`)}`,
    `description: ${yamlString(description)}`,
    `argument-hint: ${yamlString(argumentHint)}`,
    "---",
    "",
    "<!-- Generated by scripts/compile-commands.mjs. Do not edit.",
    `     platform: ${platformId}`,
    `     command: ${commandName}`,
    `     sources: ${sources}`,
    "-->",
    "",
  ];

  for (const section of CANONICAL_SECTIONS) {
    lines.push(`## ${section}`, "", sections[section].trim(), "");
  }

  return `${lines.join("\n")}`;
}

function validateCore(rel, parsed, errors) {
  if (!parsed.frontmatter) {
    errors.push(`${rel}: missing frontmatter`);
  } else {
    const keys = Object.keys(parsed.frontmatter);
    for (const key of ["description", "argument-hint"]) {
      const value = parsed.frontmatter[key];
      if (typeof value !== "string" || value.trim() === "") {
        errors.push(`${rel}: frontmatter ${key} must be a non-empty string`);
      }
    }
    for (const key of keys) {
      if (key !== "description" && key !== "argument-hint") {
        errors.push(`${rel}: unexpected frontmatter key ${key}`);
      }
    }
  }
  validateSectionSet(rel, parsed.sectionOrder, parsed.sections, CORE_SECTIONS, errors);
}

function validateFragment(rel, parsed, errors) {
  if (parsed.frontmatter) {
    errors.push(`${rel}: fragments must not include frontmatter`);
  }
  validateSectionSet(rel, parsed.sectionOrder, parsed.sections, FRAGMENT_SECTIONS, errors);
}

function validateSectionSet(rel, found, sections, allowed, errors) {
  const unknown = found.filter((name) => !CANONICAL_SECTIONS.includes(name));
  for (const name of unknown) {
    errors.push(`${rel}: unknown section ${name}`);
  }

  const known = found.filter((name) => CANONICAL_SECTIONS.includes(name));
  const positions = known.map((name) => CANONICAL_SECTIONS.indexOf(name));
  const sorted = [...positions].sort((left, right) => left - right);
  const outOfOrder = positions.some((position, index) => position !== sorted[index]);
  if (outOfOrder || new Set(known).size !== known.length) {
    errors.push(`${rel}: sections out of order (${known.join(", ")})`);
  }

  for (const name of known) {
    if (!allowed.includes(name)) {
      errors.push(`${rel}: section ${name} does not belong in this file`);
    }
  }

  for (const name of allowed) {
    if (!found.includes(name)) {
      errors.push(`${rel}: missing section ${name}`);
      continue;
    }
    if (!sections[name] || sections[name].trim() === "") {
      errors.push(`${rel}: section ${name} is empty`);
    }
  }
}

async function loadFragments(dir, platformId, errors) {
  const fragments = new Map();
  let entries = [];
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return fragments;
  }

  for (const entry of entries.filter((item) => item.isFile() && item.name.endsWith(".md")).sort(byName)) {
    const commandName = entry.name.slice(0, -3);
    const rel = path.posix.join("platforms", platformId, "fragments", entry.name);
    if (!COMMAND_NAME.test(commandName)) {
      errors.push(`${rel}: fragment name must be kebab-case`);
      continue;
    }
    const parsed = await readMarkdown(path.join(dir, entry.name), rel, errors);
    if (!parsed) continue;
    validateFragment(rel, parsed, errors);
    fragments.set(commandName, parsed);
  }

  return fragments;
}

async function readMarkdown(file, rel, errors) {
  let text;
  try {
    text = await readFile(file, "utf8");
  } catch {
    errors.push(`${rel}: file is missing`);
    return null;
  }

  const frontmatter = splitFrontmatter(text);
  if (frontmatter.error) {
    errors.push(`${rel}: ${frontmatter.error}`);
    return { frontmatter: null, sectionOrder: [], sections: {}, body: text };
  }

  const sections = parseSections(frontmatter.body);
  return {
    frontmatter: frontmatter.values,
    sectionOrder: sections.order,
    sections: sections.body,
  };
}

function splitFrontmatter(text) {
  if (!text.startsWith("---")) return { values: null, body: text };
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { error: "frontmatter is not closed" };
  const values = {};
  for (const line of match[1].split(/\r?\n/)) {
    if (line.trim() === "") continue;
    const separated = line.match(/^([A-Za-z][A-Za-z0-9-]*):\s*(.*)$/);
    if (!separated) return { error: `frontmatter line is not key: value (${line})` };
    values[separated[1]] = unquote(separated[2].trim());
  }
  return { values, body: text.slice(match[0].length) };
}

function parseSections(body) {
  const order = [];
  const sections = {};
  const lines = body.split(/\r?\n/);
  let current = null;
  const buffer = [];

  function flush() {
    if (!current) return;
    sections[current] = buffer.join("\n").trim();
    buffer.length = 0;
  }

  for (const line of lines) {
    const heading = line.match(/^## ([A-Za-z][A-Za-z0-9-]*)\s*$/);
    if (heading) {
      flush();
      current = heading[1];
      order.push(current);
      continue;
    }
    if (current) buffer.push(line);
  }
  flush();

  for (const name of order) {
    if (sections[name].trim() === "") sections[name] = "";
  }

  return { order, body: sections };
}

async function readManifest(file, rel, directoryName, errors) {
  let text;
  try {
    text = await readFile(file, "utf8");
  } catch {
    errors.push(`${rel}: file is missing`);
    return null;
  }

  let manifest;
  try {
    manifest = JSON.parse(text);
  } catch (error) {
    errors.push(`${rel}: invalid JSON (${error.message})`);
    return null;
  }

  validateManifest(rel, directoryName, manifest, errors);
  return manifest;
}

function validateManifest(rel, directoryName, manifest, errors) {
  if (manifest === null || typeof manifest !== "object" || Array.isArray(manifest)) {
    errors.push(`${rel}: manifest must be an object`);
    return;
  }

  for (const key of Object.keys(manifest)) {
    if (!MANIFEST_FIELDS.includes(key)) errors.push(`${rel}: unknown field ${key}`);
  }

  for (const key of MANIFEST_FIELDS) {
    if (!(key in manifest)) errors.push(`${rel}: missing field ${key}`);
  }

  if (typeof manifest.id !== "string" || !PLATFORM_IDS.has(manifest.id)) {
    errors.push(`${rel}: id must be expo, flutter, android, or ios`);
  } else if (manifest.id !== directoryName) {
    errors.push(`${rel}: id ${manifest.id} does not match directory ${directoryName}`);
  }

  for (const key of ["name", "language", "templateDir", "buildTool", "releaseTool", "stringsFormat", "permissionsFile"]) {
    if (typeof manifest[key] !== "string" || manifest[key].trim() === "") {
      errors.push(`${rel}: ${key} must be a non-empty string`);
    }
  }

  if (!Array.isArray(manifest.storeTargets) || manifest.storeTargets.length === 0) {
    errors.push(`${rel}: storeTargets must be a non-empty array`);
  } else {
    const seen = new Set();
    for (const target of manifest.storeTargets) {
      if (!STORE_TARGETS.has(target)) errors.push(`${rel}: storeTargets contains ${target}`);
      if (seen.has(target)) errors.push(`${rel}: storeTargets contains duplicate ${target}`);
      seen.add(target);
    }
  }

  if (!Array.isArray(manifest.commands)) {
    errors.push(`${rel}: commands must be an array`);
  } else {
    for (const commandName of manifest.commands) {
      if (typeof commandName !== "string" || !COMMAND_NAME.test(commandName)) {
        errors.push(`${rel}: commands contains invalid name ${commandName}`);
      }
    }
  }

  if (!Array.isArray(manifest.envChecks)) {
    errors.push(`${rel}: envChecks must be an array`);
  } else {
    manifest.envChecks.forEach((check, index) => validateEnvCheck(rel, index, check, errors));
  }

  if (manifest.services === null || typeof manifest.services !== "object" || Array.isArray(manifest.services)) {
    errors.push(`${rel}: services must be an object`);
  } else {
    for (const key of Object.keys(manifest.services)) {
      if (!SERVICE_KEYS.includes(key)) errors.push(`${rel}: unknown services.${key}`);
    }
    for (const key of SERVICE_KEYS) {
      const value = manifest.services[key];
      if (typeof value !== "string" || value.trim() === "") {
        errors.push(`${rel}: services.${key} must be a non-empty string`);
      }
    }
  }
}

function validateEnvCheck(rel, index, check, errors) {
  const label = `envChecks[${index}]`;
  if (check === null || typeof check !== "object" || Array.isArray(check)) {
    errors.push(`${rel}: ${label} must be an object`);
    return;
  }
  for (const key of Object.keys(check)) {
    if (!["command", "expected", "install"].includes(key)) {
      errors.push(`${rel}: ${label} has unknown field ${key}`);
    }
  }
  for (const key of ["command", "expected"]) {
    if (typeof check[key] !== "string" || check[key].trim() === "") {
      errors.push(`${rel}: ${label}.${key} must be a non-empty string`);
    }
  }
  if (check.install === null || typeof check.install !== "object" || Array.isArray(check.install)) {
    errors.push(`${rel}: ${label}.install must be an object`);
    return;
  }
  for (const key of Object.keys(check.install)) {
    if (!OS_KEYS.includes(key)) errors.push(`${rel}: ${label}.install has unknown OS ${key}`);
  }
  for (const key of OS_KEYS) {
    const hint = check.install[key];
    if (typeof hint !== "string" || hint.trim() === "") {
      errors.push(`${rel}: ${label}.install.${key} must be a non-empty string`);
    } else if (!hint.includes("Minimum:")) {
      errors.push(`${rel}: ${label}.install.${key} must include a Minimum: version`);
    }
  }
}

async function lintTemplate(root, platform, errors) {
  const templateDir = platform.manifest?.templateDir;
  if (typeof templateDir !== "string" || templateDir.trim() === "") return;

  const absolute = path.resolve(root, templateDir);
  const relative = path.relative(root, absolute);
  if (relative.startsWith("..") || path.isAbsolute(relative)) {
    errors.push(`${platform.rel}: templateDir must stay inside the repository`);
    return;
  }

  const readmePath = path.join(absolute, "README.md");
  let readme;
  try {
    readme = await readFile(readmePath, "utf8");
  } catch {
    errors.push(`${platform.rel}: ${templateDir}/README.md is missing`);
    return;
  }

  for (const token of ["{{appName}}", "{{applicationId}}", "{{primaryColor}}"]) {
    if (!readme.includes(token)) {
      errors.push(`${platform.rel}: ${templateDir}/README.md must contain ${token}`);
    }
  }
}

function yamlString(value) {
  if (/^[A-Za-z0-9][A-Za-z0-9 .,'()/_-]*$/.test(value)) return value;
  return JSON.stringify(value);
}

function unquote(value) {
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }
  return value;
}

function byName(left, right) {
  return left.name.localeCompare(right.name);
}
